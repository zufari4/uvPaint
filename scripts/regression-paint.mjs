import { _electron as electron } from 'playwright';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const server=await createServer();await server.listen();
const env={...process.env,UVPAINT_DEV_URL:'http://127.0.0.1:5173'};delete env.ELECTRON_RUN_AS_NODE;
const app=await electron.launch({args:['.',`--user-data-dir=${process.cwd()}/test-results/paint-profile`],env});
try {
  const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>errors.push(e.message));await page.waitForSelector('.empty-canvas');
  const results=await page.evaluate(async()=>{
    const {Editor}=await import('/src/core/editor.ts');const {PaintStroke}=await import('/src/tools/paint.ts');
    const {context,canvas}=await import('/src/core/canvas.ts');
    const e=new Editor(),checks=[];const ok=(v,label)=>{if(!v)throw Error(label);checks.push(label);};
    const pixel=(c,x,y)=>[...context(c).getImageData(x,y,1,1).data];
    const frame=()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)));
    await e.newCanvas(2048,2048);e.doc.restrict=false;e.tool='brush';e.color='#ff0000';e.brushSize=24;e.brushOpacity=.5;
    const original=e.layer.canvas,history=e.history.undoStack.length,revision=e.pixelsRevision;
    let allocations=0;const create=document.createElement.bind(document);
    document.createElement=function(name,...args){if(name==='canvas')allocations++;return create(name,...args);};
    const start=performance.now();
    const stroke=new PaintStroke(e,{x:100,y:100}),working=e.layer.canvas;
    const initialAllocations=allocations;
    for(let i=1;i<=240;i++)stroke.draw({x:100+i*4,y:100});
    ok(allocations===initialAllocations&&working===e.layer.canvas,'240 brush events reuse the same buffers without allocating full-size canvases');
    ok(e.pixelsRevision===revision,'Pointer events defer compositing to the animation frame');
    await frame();
    ok(e.pixelsRevision===revision+1,'Burst of pointer events produces one preview update');
    stroke.draw({x:100,y:100});await frame();stroke.finish();
    document.createElement=create;
    const elapsed=performance.now()-start;
    ok([100,300,700,1060].every(x=>Math.abs(pixel(e.layer.canvas,x,100)[3]-128)<=1),'Stroke remains continuous and 50% opacity does not build up over itself');
    ok(pixel(original,300,100)[3]===0&&pixel(e.layer.canvas,300,200)[3]===0,'Painting preserves history source pixels and pixels outside the brush');
    ok(e.history.undoStack.length===history+1,'One stroke creates one undo step');
    e.undo();ok(e.layer.canvas===original,'Undo restores the original full-resolution layer');e.redo();
    ok(pixel(e.layer.canvas,300,100)[3]===128,'Redo restores the complete stroke');
    e.addEmpty();context(e.layer.canvas).fillStyle='#ff0000';context(e.layer.canvas).fillRect(250,80,200,40);
    e.tool='clone';e.cloneSource={x:300,y:100};e.brushOpacity=.5;
    const stamp=new PaintStroke(e,{x:300,y:300});stamp.draw({x:350,y:300});stamp.finish();
    ok(pixel(e.layer.canvas,300,300)[0]===255&&pixel(e.layer.canvas,350,300)[3]===255,'Clone stamp copies the source along its path at full strength');
    e.tool='eraser';e.brushOpacity=.5;const beforeErase=e.layer.canvas;
    const erase=new PaintStroke(e,{x:300,y:300});erase.draw({x:350,y:300});await frame();erase.draw({x:300,y:300});erase.finish();
    ok(pixel(e.layer.canvas,300,300)[3]===0&&pixel(e.layer.canvas,300,100)[3]===255,'Eraser ignores the color alpha and changes nothing outside its path');
    e.undo();ok(e.layer.canvas===beforeErase,'Eraser Undo restores exact previous pixels');
    const beforeCancel=e.layer.canvas,undoCount=e.history.undoStack.length;
    const canceled=new PaintStroke(e,{x:300,y:300});canceled.draw({x:350,y:300});canceled.cancel();await frame();
    ok(e.layer.canvas===beforeCancel&&e.history.undoStack.length===undoCount,'Cancel drops queued frames and restores pixels without adding history');
    e.tool='brush';e.brushOpacity=1;e.color='#00ff00';
    e.doc.islands=[{id:0,triangles:[[{x:0,y:0},{x:.5,y:0},{x:.5,y:1}],[{x:0,y:0},{x:.5,y:1},{x:0,y:1}]]}];
    e.setLayerIsland(0);e.doc.selection=canvas(2048,2048);context(e.doc.selection).fillStyle='#fff';context(e.doc.selection).fillRect(0,500,2048,100);
    const clipped=new PaintStroke(e,{x:900,y:550});clipped.draw({x:1100,y:550});clipped.draw({x:900,y:650});clipped.finish();
    ok(pixel(e.layer.canvas,950,550)[1]===255&&pixel(e.layer.canvas,1050,550)[3]===0&&pixel(e.layer.canvas,950,625)[3]===0,'Painting obeys both the bound UV island and pixel selection');
    await e.sample();await e.newCanvas(2048,2048);e.tool='brush';e.brushOpacity=1;
    const slot=e.model.slots.find(s=>s.id===e.activeId);const live=new PaintStroke(e,{x:500,y:500});await frame();
    ok(slot.texture.image.width===512,'3D preview uses a smaller texture during the stroke');live.finish();
    ok(slot.texture.image.width===2048&&e.layer.canvas.width===2048,'Finishing restores full-resolution 3D preview and retains full-resolution pixels');
    return {checks,elapsed:Math.round(elapsed),allocations};
  });
  results.checks.forEach(label=>console.log('PASS',label));console.log(`2048x2048: ${results.elapsed} ms for 240 moves, preview frames and finish; ${results.allocations} canvas allocations total`);
  assert.deepEqual(errors,[]);
} finally {await app.close();await server.close();}
