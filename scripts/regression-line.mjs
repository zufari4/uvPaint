import { _electron as electron } from 'playwright';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const server=await createServer();await server.listen();
const env={...process.env,UVPAINT_DEV_URL:'http://127.0.0.1:5173'};delete env.ELECTRON_RUN_AS_NODE;
const app=await electron.launch({args:['.',`--user-data-dir=${process.cwd()}/test-results/line-profile`],env});
try {
  const page=await app.firstWindow();await page.waitForSelector('.empty-canvas');
  await page.evaluate(async()=>{window.__e=(await import('/src/core/editor.ts')).editor;});
  await page.evaluate(async()=>{const e=window.__e;await e.newCanvas(100,100);e.addEmpty();e.color='#ff0000';e.brushSize=4;e.brushOpacity=1;});
  await page.keyboard.press('n');
  assert.equal(await page.evaluate(()=>window.__e.tool),'line');
  await page.getByTitle('Fit canvas',{exact:true}).click();
  const b=await page.getByTestId('texture-canvas').boundingBox();
  const zoom=Math.min((b.width-100)/100,(b.height-100)/100);
  const screen=(x,y)=>[b.x+(b.width-100*zoom)/2+x*zoom,b.y+(b.height-100*zoom)/2+y*zoom];
  await page.mouse.move(...screen(10,20));await page.mouse.down();
  await page.mouse.move(...screen(60,80),{steps:4});await page.mouse.move(...screen(90,22),{steps:4});
  await page.mouse.up();
  const line=await page.evaluate(()=>{const e=window.__e,d=e.layer.canvas.getContext('2d');const a=(x,y)=>d.getImageData(x,y,1,1).data[3];
    return {mid:a(50,21),detour:a(45,60),undo:e.history.undoStack.at(-1)?.label};});
  assert.ok(line.mid>200,'line passes through the midpoint');
  assert.equal(line.detour,0,'intermediate pointer positions leave no trace');
  assert.equal(line.undo,'Line');
  console.log('PASS Line tool draws one straight segment between press and release');
  await page.keyboard.down('Shift');
  await page.mouse.move(...screen(10,50));await page.mouse.down();
  await page.mouse.move(...screen(80,53),{steps:4});await page.mouse.up();
  await page.keyboard.up('Shift');
  const snapped=await page.evaluate(()=>{const d=window.__e.layer.canvas.getContext('2d');return [d.getImageData(78,50,1,1).data[3],d.getImageData(78,53,1,1).data[3]];});
  assert.ok(snapped[0]>200&&snapped[1]===0,'Shift snaps the line to horizontal');
  console.log('PASS Shift snaps lines to 45° steps');
  await page.keyboard.press('b');
  const [px,py]=screen(50,50);
  await page.mouse.move(px,py);
  await page.keyboard.press('f');
  await page.locator('.brush-footprint[data-size]').waitFor();
  await page.mouse.move(px+20*zoom,py,{steps:3});
  const resized=await page.evaluate(()=>window.__e.brushSize);
  assert.ok(Math.abs(resized-44)<=2,`brush size follows the pointer (${resized})`);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>window.__e.brushSize),4);
  console.log('PASS F resize previews the size and Escape restores it');
  const strokes=await page.evaluate(()=>window.__e.history.undoStack.length);
  await page.mouse.move(px,py);
  await page.keyboard.press('f');
  await page.mouse.move(px+10*zoom,py,{steps:3});
  await page.mouse.click(px+10*zoom,py);
  const applied=await page.evaluate(()=>({size:window.__e.brushSize,undo:window.__e.history.undoStack.length}));
  assert.ok(Math.abs(applied.size-24)<=2,`click applies the size (${applied.size})`);
  assert.equal(applied.undo,strokes,'the confirming click does not paint');
  assert.equal(await page.locator('.brush-footprint[data-size]').count(),0);
  console.log('PASS Click applies the new brush size without painting');
} finally {await app.close();await server.close();}
