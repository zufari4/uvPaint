import { _electron as electron } from 'playwright';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
const server=await createServer();await server.listen();
const env={...process.env,UVPAINT_DEV_URL:'http://127.0.0.1:5173'};delete env.ELECTRON_RUN_AS_NODE;
const app=await electron.launch({args:['.',`--user-data-dir=${process.cwd()}/test-results/line-profile`],env});
try {
  const page=await app.firstWindow();await page.waitForSelector('.empty-canvas');
  await page.evaluate(async()=>{window.__e=(await import('/src/core/editor.ts')).editor;});
  await page.evaluate(async()=>{const e=window.__e;await e.newCanvas(100,100);e.addEmpty();e.color='#ff0000';e.brushSize=4;e.brushOpacity=1;e.setShape({kind:'line',fill:'none',outline:true,sides:6});});
  await page.keyboard.press('n');
  assert.equal(await page.evaluate(()=>window.__e.tool),'line');
  await page.getByTitle('Fit canvas',{exact:true}).click();
  let b=await page.getByTestId('texture-canvas').boundingBox();
  const zoom=Math.min((b.width-100)/100,(b.height-100)/100);
  const screen=(x,y)=>[b.x+(b.width-100*zoom)/2+x*zoom,b.y+(b.height-100*zoom)/2+y*zoom];
  await page.mouse.move(...screen(10,20));await page.mouse.down();
  await page.mouse.move(...screen(60,80),{steps:4});await page.mouse.move(...screen(90,22),{steps:4});
  await page.mouse.up();await page.keyboard.press('Enter');
  const line=await page.evaluate(()=>{const e=window.__e,d=e.layer.canvas.getContext('2d');const a=(x,y)=>d.getImageData(x,y,1,1).data[3];
    return {mid:a(50,21),detour:a(45,60),undo:e.history.undoStack.at(-1)?.label};});
  assert.ok(line.mid>200,'line passes through the midpoint');
  assert.equal(line.detour,0,'intermediate pointer positions leave no trace');
  assert.equal(line.undo,'Line');
  console.log('PASS Line tool draws one straight segment between press and release');
  await page.keyboard.down('Shift');
  await page.mouse.move(...screen(10,50));await page.mouse.down();
  await page.mouse.move(...screen(80,53),{steps:4});await page.mouse.up();
  await page.keyboard.up('Shift');await page.keyboard.press('Enter');
  const snapped=await page.evaluate(()=>{const d=window.__e.layer.canvas.getContext('2d');return [d.getImageData(78,50,1,1).data[3],d.getImageData(78,53,1,1).data[3]];});
  assert.ok(snapped[0]>200&&snapped[1]===0,'Shift snaps the line to horizontal');
  console.log('PASS Shift snaps lines to 45° steps');
  const drag=async(from,to,shift=false)=>{
    b=await page.getByTestId('texture-canvas').boundingBox();
    if(shift)await page.keyboard.down('Shift');
    await page.mouse.move(...screen(...from));await page.mouse.down();
    await page.mouse.move(...screen(...to),{steps:4});await page.mouse.up();
    if(shift)await page.keyboard.up('Shift');
    await page.keyboard.press('Enter');
  };
  const pickShape=async name=>{
    await page.locator('.tool-shapes > button').click({button:'right'});
    await page.getByRole('menuitemradio',{name}).click();
    assert.equal(await page.locator('.tool-flyout').count(),0,'choosing a shape closes the flyout');
  };
  const alpha=(points)=>page.evaluate(points=>{const d=window.__e.layer.canvas.getContext('2d');
    return points.map(([x,y])=>[...d.getImageData(x,y,1,1).data]);},points);
  await pickShape('Rectangle');
  assert.equal(await page.evaluate(()=>window.__e.tool+'/'+window.__e.shape.kind),'line/rect');
  await page.evaluate(()=>{window.__e.addEmpty();window.__e.brushSize=2;});
  await drag([20,20],[60,50]);
  const rect=await alpha([[20,35],[40,20],[40,35],[70,35]]);
  assert.ok(rect[0][3]>100&&rect[1][3]>100,'rectangle outline is drawn');
  assert.ok(rect[2][3]===0&&rect[3][3]===0,'unfilled rectangle stays empty inside and outside');
  assert.equal(await page.evaluate(()=>window.__e.history.undoStack.at(-1)?.label),'Rectangle');
  console.log('PASS Rectangle shape draws an outline between two corners');
  await pickShape('Ellipse');
  await page.evaluate(()=>{window.__e.addEmpty();window.__e.backgroundColor='#0000ff';});
  await page.getByLabel('Shape fill').selectOption('secondary');
  await drag([10,10],[50,30],true);
  const circle=await alpha([[30,30],[30,9],[13,13],[30,52]]);
  assert.ok(circle[0][2]>200&&circle[0][0]<50,'circle is filled with the secondary color');
  assert.ok(circle[1][0]>200,'outline uses the primary color');
  assert.equal(circle[2][3],0,'circle corners stay empty');
  assert.ok(circle[3][3]===0,'Shift turns the ellipse into a circle (no stretch beyond the square box)');
  console.log('PASS Shift draws a filled circle with an outline');
  await pickShape('Regular polygon');
  await page.evaluate(()=>window.__e.addEmpty());
  await page.getByLabel('Polygon sides').fill('4');
  await drag([50,50],[70,50]);
  const diamond=await alpha([[50,50],[66,66],[68,50]]);
  assert.ok(diamond[0][2]>200,'polygon is filled');
  assert.equal(diamond[1][3],0,'four-sided polygon from centre to vertex is a diamond');
  assert.ok(diamond[2][3]>200,'polygon vertex reaches the dragged point');
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('uvpaint.toolOptions')).shape.kind),'polygon','chosen shape is remembered');
  assert.match(await page.locator('.tool-shapes > button').getAttribute('title'),/^Regular polygon \(N\)/);
  console.log('PASS Regular polygon uses the side count and the chosen shape is remembered');
  await pickShape('Line');
  await page.evaluate(()=>{window.__e.brushSize=4;});
  await page.keyboard.press('b');
  b=await page.getByTestId('texture-canvas').boundingBox();
  const [px,py]=screen(50,50);
  await page.mouse.move(px,py);
  await page.keyboard.press('f');
  await page.locator('.brush-footprint[data-size]').waitFor();
  await page.mouse.move(px+20*zoom,py,{steps:3});
  const resized=await page.evaluate(()=>window.__e.brushSize);
  assert.ok(Math.abs(resized-44)<=2,`brush size follows the pointer (${resized})`);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(()=>window.__e.brushSize),4);
  console.log('PASS F resize previews the size and Escape restores it');
  const strokes=await page.evaluate(()=>window.__e.history.undoStack.length);
  await page.mouse.move(px,py);
  await page.keyboard.press('f');
  await page.mouse.move(px+10*zoom,py,{steps:3});
  await page.mouse.click(px+10*zoom,py);
  const applied=await page.evaluate(()=>({size:window.__e.brushSize,undo:window.__e.history.undoStack.length}));
  assert.ok(Math.abs(applied.size-24)<=2,`click applies the size (${applied.size})`);
  assert.equal(applied.undo,strokes,'the confirming click does not paint');
  assert.equal(await page.locator('.brush-footprint[data-size]').count(),0);
  console.log('PASS Click applies the new brush size without painting');
} finally {await app.close();await server.close();}
